#!/usr/bin/env python3
"""Generate data-only Agda RawRun terms from JSON contract fixtures.

Reads fixtures/valid/*.json and fixtures/invalid-semantic/*.json, maps string
IDs to dense naturals per namespace (by first appearance in a fixed
traversal), and emits one data-only Agda module per fixture under
Generated/Raw/<Category>/<Name>.agda.

invalid-schema/ fixtures are intentionally ignored (they do not decode).
The output is deterministic (sorted traversal, ordered ID assignment) and
contains raw terms only -- never well-formedness or proofs. Build-time tool,
stdlib only, not shipped.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent                 # .../RuntimeContract/Serialization
FIXTURES = HERE / "fixtures"
GEN_ROOT = HERE.parent / "Generated" / "Raw"           # .../RuntimeContract/Generated/Raw
MODULE_PREFIX = "RuntimeContract.Generated.Raw"

FORMAT_CODES = {"hoapa.trace/0": 0}
CATEGORIES = {"valid": "Valid", "invalid-semantic": "InvalidSemantic"}


class NS:
    """A single ID namespace: assigns dense naturals by first appearance."""

    def __init__(self) -> None:
        self.m: dict[str, int] = {}

    def of(self, s: str) -> int:
        if s not in self.m:
            self.m[s] = len(self.m)
        return self.m[s]


def snake_to_camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def nat_list(xs: list[int]) -> str:
    return "[]" if not xs else "(" + " ∷ ".join(str(x) for x in xs) + " ∷ [])"


def record_list(strs: list[str]) -> str:
    return "[]" if not strs else "(" + " ∷ ".join(strs) + " ∷ [])"


def build_term(run: dict) -> str:
    actor, event, conv = NS(), NS(), NS()
    stag, ctag, prov = NS(), NS(), NS()
    runid, proto, sib = NS(), NS(), NS()

    fmt = FORMAT_CODES.get(run["traceFormat"], 1)
    rid = runid.of(run["runId"])
    pid = proto.of(run["protocolId"])
    sibs = [sib.of(s) for s in run["siblingProtocolIds"]]
    actor_ids = [actor.of(a) for a in run["trace"]["actorIds"]]

    conv_strs = []
    for c in run["trace"]["conversations"]:
        cid = conv.of(c["conversationId"])
        cacts = [actor.of(a) for a in c["actorIds"]]
        cst = stag.of(c["sessionTag"])
        conv_strs.append(f"(mkConv {cid} {nat_list(cacts)} {cst})")

    ev_strs = []
    for e in run["trace"]["events"]:
        eid = event.of(e["eventId"])
        ecid = conv.of(e["conversationId"])
        touches = [actor.of(a) for a in e["touches"]]
        parents = [event.of(x) for x in e["causalParents"]]
        ect = ctag.of(e["contentTag"])
        epr = prov.of(e["provenanceToken"])
        ev_strs.append(
            f"(mkEvent {eid} {ecid} {nat_list(touches)} {nat_list(parents)} {ect} {epr})"
        )

    trace = f"(mkTrace {nat_list(actor_ids)} {record_list(conv_strs)} {record_list(ev_strs)})"
    return f"mkRun {fmt} {rid} {pid} {nat_list(sibs)} {trace}"


def emit(category_dir: str, camel: str, term: str, src_rel: str) -> Path:
    cat = CATEGORIES[category_dir]
    out_dir = GEN_ROOT / cat
    out_dir.mkdir(parents=True, exist_ok=True)
    mod = f"{MODULE_PREFIX}.{cat}.{camel}"
    content = (
        "{-# OPTIONS --cubical --safe --guardedness #-}\n\n"
        "-- GENERATED by Serialization/generate_raw_agda.py\n"
        f"-- Source fixture: {src_rel}\n"
        "-- DO NOT EDIT. Data only: this module must define raw RawRun terms and\n"
        "-- must never mention well-formedness or proofs (CI grep-guards this).\n\n"
        f"module {mod} where\n\n"
        "open import Cubical.Data.Nat using (ℕ; zero; suc)\n"
        "open import Cubical.Data.List using (List; []; _∷_)\n"
        "open import RuntimeContract.Trace\n\n"
        "term : RawRun\n"
        f"term = {term}\n"
    )
    out_path = out_dir / f"{camel}.agda"
    out_path.write_text(content, encoding="utf-8")
    return out_path


def main() -> None:
    # Clear generated output first so deleted/renamed fixtures cannot leave
    # stale modules behind (drift and orphans then collapse into one git gate).
    if GEN_ROOT.exists():
        shutil.rmtree(GEN_ROOT)
    for category_dir in sorted(CATEGORIES):
        d = FIXTURES / category_dir
        if not d.is_dir():
            continue
        for f in sorted(d.glob("*.json")):
            run = json.loads(f.read_text(encoding="utf-8"))
            camel = snake_to_camel(f.stem)
            term = build_term(run)
            emit(category_dir, camel, term, f"fixtures/{category_dir}/{f.name}")
            print(f"generated {category_dir}/{f.name} -> {CATEGORIES[category_dir]}/{camel}.agda")


if __name__ == "__main__":
    main()
